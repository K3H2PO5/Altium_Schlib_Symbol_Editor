def tr(lang: str, key: str, **kwargs: object) -> str:
    table = TEXT.get(lang) or TEXT["zh"]
    template = table.get(key) or TEXT["zh"][key]
    if not kwargs:
        return template
    return template.format(**kwargs)


def localize_note(lang: str, note: str) -> str:
    if lang != "en" or note == TEXT["zh"]["unchanged_note"]:
        return note
    for pattern, key, fields in _NOTE_PATTERNS:
        match = pattern.match(note)
        if match:
            values = {name: match.group(index + 1) for index, name in enumerate(fields)}
            return tr(lang, key, **values)
    return note


def localize_error(lang: str, message: str) -> str:
    if lang != "en":
        return message
    for pattern, key, fields in _ERROR_PATTERNS:
        match = pattern.match(message)
        if not match:
            continue
        values: dict[str, object] = {}
        for name, source in fields.items():
            if name == "label_key":
                values["label"] = tr(lang, str(source))
            else:
                values[name] = match.group(int(source))
        return tr(lang, key, **values)
    return message
